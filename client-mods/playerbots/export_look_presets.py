"""Export the client's own character-creation presets as recruit looks.

Data/custompreset/custompreset.pak holds complete player looks made for the
creation screen: model choices, colours, height and 43 slider bytes in the
same order the client sends them at character creation (jaw line first). A
recruit that takes one of these gets a face and body of its own instead of its
owner's, and the sliders are known-good combinations.

Usage: python export_look_presets.py --client <client> --output <look-presets.txt>
One line per look: RACE GENDER face hair deco tattoo skin hair lip eye height detail-hex.
Colours are the server's integers (blue << 16 | green << 8 | red).
"""
import argparse
import re
import sys
from pathlib import Path
import xml.etree.ElementTree as E

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'expanded-warehouse'))
from codec import binary_xml, read_pak  # noqa: E402

KINDS = {'pc_lm': ('ELYOS', 'MALE'), 'pc_lf': ('ELYOS', 'FEMALE'), 'pc_dm': ('ASMODIANS', 'MALE'), 'pc_df': ('ASMODIANS', 'FEMALE')}
# Player presets only: NPC presets use head models players do not have, and the
# "body", "normal" and "fanatic" sets are partial templates for the sliders screen.
PLAYER_FILE = re.compile(r'^preset_(lm|lf|dm|df)\d+\.xml$')
DETAIL_BYTES = 43
RESERVED = (37, 42)  # always zero in the creation packet


def colour(text):
    red, green, blue = (int(part) for part in text.split(','))
    if not all(0 <= value <= 255 for value in (red, green, blue)):
        raise ValueError('colour out of range: ' + text)
    return blue << 16 | green << 8 | red


def looks(client):
    rows = []
    with read_pak(Path(client) / 'Data/custompreset/custompreset.pak') as archive:
        for name in sorted(archive.namelist()):
            if not PLAYER_FILE.match(name.lower()):
                continue
            data = archive.read(name)
            root = binary_xml(data) if data[:1] == b'\x80' else E.fromstring(data)
            for preset in root.iter('custom_preset'):
                get = lambda tag: (preset.findtext(tag) or '').strip()
                kind = KINDS.get(get('pc_type'))
                detail = get('detail').lower()
                if kind is None or get('npc_head_type') not in ('', '0') or get('npc_hair_type') not in ('', '0'):
                    continue
                if not re.fullmatch('[0-9a-f]{%d}' % (DETAIL_BYTES * 2), detail):
                    continue
                raw = bytes.fromhex(detail)
                if any(raw[i] for i in RESERVED):
                    continue
                height = float(get('scale'))
                models = [int(get(tag)) for tag in ('face_type', 'hair_type', 'feat_type1', 'feat_type2')]
                if not 0.8 <= height <= 1.25 or not all(0 <= value <= 255 for value in models):
                    continue
                rows.append((kind[0], kind[1], *models, colour(get('skin_color')), colour(get('hair_color')),
                             colour(get('lip_color')), colour(get('eye_color')), height, detail))
    return sorted(set(rows))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    rows = looks(args.client)
    lines = ['# Generated by client-mods/playerbots/export_look_presets.py from the client creation presets.',
             '# RACE GENDER face hair deco tattoo skin hair lip eye height detail']
    lines += ['%s %s %d %d %d %d %d %d %d %d %.6f %s' % row for row in rows]
    args.output.write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    counts = {}
    for row in rows:
        counts[row[:2]] = counts.get(row[:2], 0) + 1
    print(len(rows), 'looks:', ', '.join('%s %s %d' % (race, gender, n) for (race, gender), n in sorted(counts.items())))


if __name__ == '__main__':
    main()
